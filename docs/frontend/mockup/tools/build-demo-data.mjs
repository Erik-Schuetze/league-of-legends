#!/usr/bin/env node
/**
 * Turns the repository's demo artifacts (fixtures/site/v1) into a typed module
 * the review mockup can import at build time.
 *
 * The mockup must render deterministically for screenshots and must not make
 * any network request, so the artifacts are inlined rather than fetched.
 *
 * Usage, from docs/frontend/mockup:
 *   node tools/build-demo-data.mjs
 */
import { execSync } from "node:child_process";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = execSync("git rev-parse --show-toplevel", {
  cwd: here,
  encoding: "utf8",
}).trim();
const fixture = join(repo, "fixtures", "site", "v1");

const PATCH = "16.18";
const REGION = "EUW";
const QUEUE = 420;
const BRACKET = "all";
const partition = join(fixture, "p", PATCH, REGION, String(QUEUE), BRACKET);

const read = (p) => JSON.parse(readFileSync(p, "utf8"));

const manifest = read(join(fixture, "manifest.json"));
const manifestPartition = manifest.partitions.find(
  (p) => p.patch === PATCH && p.region === REGION && p.queue === QUEUE && p.bracket === BRACKET,
);
const tierlist = read(join(partition, "tierlist.json"));
const patches = read(join(fixture, "static", "16.18.1", "patches.json"));
const catalogue = read(join(fixture, "static", "16.18.1", "champions.json"));

/** Champion pages to inline: a spread across roles, tiers and item counts. */
const DETAIL_IDS = [1, 33, 63, 101, 141, 240, 427, 523, 555, 800];
const TOP = 5;
const trim = (rows = []) => rows.slice(0, TOP);

const championPages = DETAIL_IDS.map((id) => {
  const page = read(join(partition, "champions", `${id}.json`));
  return {
    champion_id: page.champion_id,
    champion_slug: page.champion_slug,
    roles: page.roles.map((r) => ({
      role: r.role,
      stats: r.stats,
      items: trim(r.items),
      runes: trim(r.runes),
      spells: trim(r.spells),
      skill_orders: trim(r.skill_orders),
    })),
  };
});

const cellCount = tierlist.cells.length;
const roles = ["TOP", "JUNGLE", "MID", "BOTTOM", "SUPPORT"];

/* The artifact reports a withheld count but never emits the withheld cells, so
   the only thing the interface can honestly show per champion/role is a gap.
   This is the set difference between what the champion catalogue suggests is
   possible and what the build actually published. */
const published = new Set(
  tierlist.cells.map((c) => `${c.champion_id}:${c.role}`),
);
const unpublishedPairs = catalogue.champions
  .flatMap((c) => (c.roles ?? []).map((role) => ({ champion_id: c.id, role })))
  .filter((p) => !published.has(`${p.champion_id}:${p.role}`))
  .slice(0, 24);

const body = `// GENERATED by tools/build-demo-data.mjs from fixtures/site/v1. Do not edit.
//
// Provenance: demo artifacts, not live data. The mockup labels every surface
// that consumes this module with a provenance line.

export type Role = "TOP" | "JUNGLE" | "MID" | "BOTTOM" | "SUPPORT";
export type Tier = "S+" | "S" | "A" | "B" | "C" | "D";

export interface SourceWindow { from: string; to: string; }

export interface Coverage {
  patch: string; region: string; queue: number; bracket: string;
  generated_at: string; source_window: SourceWindow;
  min_cell_n: number; suppressed_cells: number; cells_published: number;
  build_run_id: number; git_sha: string;
}

export interface Cell {
  champion_id: number; role: Role; n: number; wins: number;
  win_rate: number; pick_rate: number; ban_rate: number;
  tier: Tier; ci95_half_width: number;
}

export interface RankedRow {
  kind?: string; key?: Array<number | string>; label?: string; order?: string;
  n: number; wins: number; win_rate: number;
}

export interface ChampionRolePage {
  champion_id: number; champion_slug: string;
  roles: Array<{
    role: Role; stats: Cell; items: RankedRow[];
    runes: RankedRow[]; spells: RankedRow[]; skill_orders: RankedRow[];
  }>;
}

export const coverage: Coverage = ${JSON.stringify(
  {
    patch: tierlist.patch,
    region: tierlist.region,
    queue: tierlist.queue,
    bracket: tierlist.bracket,
    generated_at: tierlist.generated_at,
    source_window: tierlist.source_window,
    min_cell_n: tierlist.min_cell_n,
    suppressed_cells: tierlist.suppressed_cells,
    cells_published: manifestPartition?.cells_published ?? tierlist.cells.length,
    build_run_id: manifestPartition?.build_run_id ?? 0,
    git_sha: manifestPartition?.git_sha ?? "",
  },
  null,
  2,
)};

export const dataSource = ${JSON.stringify(manifest.source)};

export const generatedAt = ${JSON.stringify(manifest.generated_at)};

/** Every partition the build published. A partition absent from this list has
 *  no published data at all, which is a distinct state from an empty filter. */
export const partitions = ${JSON.stringify(
  manifest.partitions.map((p) => ({
    patch: p.patch, region: p.region, queue: p.queue, bracket: p.bracket,
    cells_published: p.cells_published, suppressed_cells: p.suppressed_cells,
  })),
  null,
  2,
)} as const;

export const regions = ${JSON.stringify([...new Set(manifest.partitions.map((p) => p.region))])};
export const queues: Array<{ id: number; label: string }> = [
  { id: 420, label: "Ranked Solo/Duo" },
  { id: 440, label: "Ranked Flex" },
  { id: 400, label: "Normal Draft" },
];
export const brackets = ${JSON.stringify([...new Set(manifest.partitions.map((p) => p.bracket))])};
export const patchesAvailable = ${JSON.stringify(patches.patches)};
export const latestPatch = ${JSON.stringify(patches.latest)};
export const ddragonVersion = ${JSON.stringify(patches.ddragon_version)};
export const roles: Role[] = [${roles.map((r) => JSON.stringify(r)).join(", ")}];
export const tiers: Tier[] = ["S+", "S", "A", "B", "C", "D"];

export interface Champion { id: number; key: string; slug: string; name: string; roles: Role[]; }

export const champions: Champion[] = ${JSON.stringify(
  catalogue.champions.map((c) => ({
    id: c.id, key: c.key, slug: c.slug, name: c.name, roles: c.roles,
  })),
  null,
  2,
)};

export const championById = new Map(champions.map((c) => [c.id, c]));

export const cells: Cell[] = ${JSON.stringify(tierlist.cells, null, 2)};

export const championPages: ChampionRolePage[] = ${JSON.stringify(championPages, null, 1)};

export const cellCount = ${cellCount};

/** Champion/role pairs the catalogue allows but this build did not publish.
 *  A withheld cell is never emitted, never zero: the interface shows the gap
 *  and states \`suppressed_cells\` as a count in the suppression summary. */
export const unpublishedPairs: Array<{ champion_id: number; role: Role }> = ${JSON.stringify(
  unpublishedPairs,
  null,
  1,
)};
`;

const out = join(here, "..", "src", "lib", "data", "demo.generated.ts");
writeFileSync(out, body);
console.log(
  `wrote ${out}\n  ${cellCount} cells, ${championPages.length} champion pages, ` +
    `${catalogue.champions.length} champions, ${manifest.partitions.length} partitions, ` +
    `${readdirSync(join(partition, "matchups")).length} matchup files available` +
    `\n  ${(body.length / 1024).toFixed(1)} KiB`,
);
